def lookup_manufacturer(byte1: int, byte2: int) -> str:
    key = (byte1, byte2)
    if key in SPD_MANUFACTURERS:
        return SPD_MANUFACTURERS[key]

    if byte2 == 0x00 and byte1 in SINGLE_BYTE_MANUFACTURERS:
        return SINGLE_BYTE_MANUFACTURERS[byte1]

    if byte1 == 0x01 and byte2 in SINGLE_BYTE_MANUFACTURERS:
        return SINGLE_BYTE_MANUFACTURERS[byte2]

    return f"Unknown ({byte1:02X}:{byte2:02X})"


def lookup_manufacturer_by_id(byte1: int, byte2: int) -> str:
    return lookup_manufacturer(byte1, byte2)


